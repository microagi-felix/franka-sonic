#!/usr/bin/env python
"""Build the lane B-2 (GR00T over SONIC) dataset from lane A's GR00T v2 dataset
plus per-episode SONIC motion-token labels.

Run it with the GR00T interpreter, which owns pyarrow / pandas / torchcodec:

    ~/Isaac-GR00T/.venv/bin/python harness/lane_b/make_sonic_dataset.py \\
        --source ~/runs/franka-sonic/shared/2026-09-03_dataset-2/out/gr00t_v2 \\
        --tokens <label_run>/out/tokens \\
        --output <label_run>/out/gr00t_v2_sonic \\
        [--modality-config-path harness/lane_b/modality_config_dual_fr3_sonic.py] \\
        [--no-stats] [--validate-max-episodes 5]

This is a *relabelling* pass, not a conversion: everything an observation is
(state columns, videos, timestamps, frame/episode/global indices, tasks) is
carried over unchanged from --source, and only the `action` table is replaced.

INPUT A: --source, a GR00T-flavored LeRobot v2.1 dataset written by
harness/data/convert_hdf5_to_gr00t_v2.py
------------------------------------------------------------------------------
    data/chunk-{ep//1000:03d}/episode_{ep:06d}.parquet
        observation.state  list<float32>[16]  [Lq7, Rq7, grip_l, grip_r]
        action             list<float32>[16]  joint targets  (REPLACED here)
        timestamp float32, frame_index/episode_index/index/task_index int64
    videos/chunk-{c:03d}/observation.images.{top,wrist_left,wrist_right}/episode_{ep:06d}.mp4
    meta/{info.json,episodes.jsonl,tasks.jsonl,modality.json,stats.json,
          relative_stats.json,provenance.json}

INPUT B: --tokens, one .npz per episode written by the SONIC labeller
------------------------------------------------------------------------------
    <tokens>/index.json          list of {episode_index, file, n_frames_dataset, clip}
    <tokens>/episode_{ep:06d}.npz
        token             float32 (T, 64)  dequantised SONIC FSQ motion token
        grip              float32 (T, 2)   [left, right], 0 = open, 1 = closed
        episode_index     int
        source_file, demo_name, clip   str
        n_frames_dataset  int

T must equal the source episode's parquet row count — a mismatch is an error,
never a silent truncation. Tokens are additionally required to be finite and to
sit inside the FSQ grid bound (|token| <= 1.25; the codebook itself is the 1/16
grid in [-1, 1], the slack only absorbs float round-trips).

OUTPUT (same layout, 66-D actions)
------------------------------------------------------------------------------
    action[t] = concat(token[t] (64), grip[t] (2))   ->  list<float32>[66]

        motion_token   0:64   64-D SONIC FSQ token
        left_grip     64:65   0 = open, 1 = closed
        right_grip    65:66   0 = open, 1 = closed

    observation.state and every index/timestamp column: copied unchanged.
    videos: copied byte-for-byte with shutil.copy2 (NOT symlinked — a fine-tune
    run must survive the label run folder being moved or archived).
    meta/info.json      source info with features.action.shape=[66],
                        features.action.names=[motion_token_00..63,
                        left_grip, right_grip] and robot_type=--robot-type.
    meta/modality.json  source state/video/annotation blocks; action block is
                        {motion_token 0:64, left_grip 64:65, right_grip 65:66}.
                        (The P3 gate greps this file for the word "token".)
    meta/episodes.jsonl, meta/tasks.jsonl   copied.
    meta/provenance.json  source provenance + tokens_dir / source_dataset /
                        per-episode clip + token file.
    meta/stats.json (+ relative_stats.json)  regenerated by gr00t/data/stats.py
                        against harness/lane_b/modality_config_dual_fr3_sonic.py
                        — never copied, the 16-D stats would mis-normalise.

Refuses to write into a directory that already holds a dataset. Nothing is ever
deleted (AGENTS.md rule o); a stale output directory is an error, not a target.
Prints `CONVERT_DONE: <N> episodes, <F> frames -> <dir>` on success and exits
non-zero on any failure.
"""

from __future__ import annotations

import argparse
import copy
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import traceback

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq


# ----------------------------------------------------------------- constants

ROBOT_TYPE = "dual_fr3_franka_hand_sonic"

TOKEN_DIM = 64  # SONIC FSQ motion token width
GRIP_DIM = 2  # [left, right]
ACTION_DIM = TOKEN_DIM + GRIP_DIM  # 66

# names for the 66-D action feature, in dataset order
ACTION_NAMES = [f"motion_token_{i:02d}" for i in range(TOKEN_DIM)] + [
    "left_grip",
    "right_grip",
]

# meta/modality.json action block — the map from the flat 66-D columns to the
# modality keys used by harness/lane_b/modality_config_dual_fr3_sonic.py.
ACTION_SPLIT = {
    "motion_token": {"start": 0, "end": TOKEN_DIM},
    "left_grip": {"start": TOKEN_DIM, "end": TOKEN_DIM + 1},
    "right_grip": {"start": TOKEN_DIM + 1, "end": ACTION_DIM},
}

# FSQ codebook is the 1/16 grid in [-1, 1]; the slack only absorbs float
# round-trips through the labeller, it is not a licence for unbounded latents.
TOKEN_ABS_MAX = 1.25

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MODALITY_CONFIG = (
    REPO_ROOT / "harness" / "lane_b" / "modality_config_dual_fr3_sonic.py"
)
DEFAULT_GR00T_ROOT = Path("~/Isaac-GR00T").expanduser()

TOKENS_INDEX_FILENAME = "index.json"


class BuildError(RuntimeError):
    """Anything that makes the produced dataset untrustworthy."""


# ------------------------------------------------------------------- helpers


def log(msg: str) -> None:
    print(msg, flush=True)


def list_column(values: np.ndarray) -> pa.Array:
    """(T,D) float32 -> arrow list<float32>, one D-vector per row.

    Same helper (and same reasoning) as harness/data/convert_hdf5_to_gr00t_v2.py:
    list<float32> (not fixed_size_list) is what LeRobot v2.1 writes and what
    makes ``pd.read_parquet`` hand each cell back as a float32 np.ndarray --
    which lerobot_episode_loader._extract_joint_groups requires
    (``isinstance(df[key].iloc[0], np.ndarray)``).
    """
    values = np.ascontiguousarray(values, dtype=np.float32)
    rows, dim = values.shape
    offsets = pa.array(np.arange(0, rows * dim + 1, dim, dtype=np.int32), type=pa.int32())
    flat = pa.array(values.reshape(-1), type=pa.float32())
    return pa.ListArray.from_arrays(offsets, flat)


def npz_str(value) -> str:
    """Decode a string stored in an .npz (0-d numpy array of dtype U/S/O)."""
    if isinstance(value, np.ndarray):
        return npz_str(value.item())
    if isinstance(value, bytes):
        return value.decode("utf-8")
    return str(value)


def npz_int(value) -> int:
    if isinstance(value, np.ndarray):
        return int(value.item())
    return int(value)


def read_jsonl(path: Path) -> list[dict]:
    if not path.is_file():
        raise BuildError(f"missing {path}")
    with open(path, "r") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def write_jsonl(path: Path, rows: list[dict]) -> None:
    with open(path, "w") as handle:
        for row in rows:
            handle.write(json.dumps(row) + "\n")


def read_json(path: Path) -> dict:
    if not path.is_file():
        raise BuildError(f"missing {path}")
    with open(path, "r") as handle:
        return json.load(handle)


# ----------------------------------------------------------------- the source


def load_source(source: Path) -> dict:
    """Read the source dataset's meta and work out its episode list."""
    meta = source / "meta"
    info = read_json(meta / "info.json")
    modality = read_json(meta / "modality.json")
    episodes = read_jsonl(meta / "episodes.jsonl")
    tasks = read_jsonl(meta / "tasks.jsonl")
    provenance: dict = {}
    if (meta / "provenance.json").is_file():
        provenance = read_json(meta / "provenance.json")

    for key in ("data_path", "video_path", "chunks_size", "fps", "features"):
        if key not in info:
            raise BuildError(f"{meta / 'info.json'}: missing '{key}'")
    if "action" not in info["features"] or "observation.state" not in info["features"]:
        raise BuildError(f"{meta / 'info.json'}: features lack action / observation.state")

    video_keys = [
        key for key, spec in info["features"].items() if spec.get("dtype") == "video"
    ]
    if not video_keys:
        raise BuildError(f"{meta / 'info.json'}: no video features found")

    if not episodes:
        raise BuildError(f"{meta / 'episodes.jsonl'}: no episodes")

    return {
        "root": source,
        "info": info,
        "modality": modality,
        "episodes": episodes,
        "tasks": tasks,
        "provenance": provenance,
        "video_keys": video_keys,
        "chunks_size": int(info["chunks_size"]),
        "data_path": info["data_path"],
        "video_path": info["video_path"],
    }


def guard_output(output: Path) -> None:
    """Refuse to write on top of an existing dataset (never delete, rule o)."""
    if not output.exists():
        return
    if not output.is_dir():
        raise BuildError(f"--output exists and is not a directory: {output}")
    existing = [
        p
        for p in (output / "meta" / "info.json", output / "meta" / "modality.json")
        if p.exists()
    ] + sorted(output.glob("data/chunk-*/episode_*.parquet"))[:1]
    if existing:
        raise BuildError(
            f"--output already contains a dataset ({existing[0]}). "
            "Refusing to overwrite; nothing on this pod is ever deleted "
            "(AGENTS.md rule o) -- pick a fresh --output directory."
        )


# ------------------------------------------------------------- token labels


def load_token_index(tokens_dir: Path) -> dict[int, dict]:
    """Read <tokens>/index.json into {episode_index: entry}."""
    index_path = tokens_dir / TOKENS_INDEX_FILENAME
    entries = read_json(index_path)
    if not isinstance(entries, list):
        raise BuildError(f"{index_path}: expected a list of entries, got {type(entries).__name__}")
    by_episode: dict[int, dict] = {}
    for entry in entries:
        if "episode_index" not in entry:
            raise BuildError(f"{index_path}: an entry has no 'episode_index': {entry}")
        ep = int(entry["episode_index"])
        if ep in by_episode:
            raise BuildError(f"{index_path}: episode_index {ep} listed twice")
        by_episode[ep] = entry
    if not by_episode:
        raise BuildError(f"{index_path}: no entries")
    return by_episode


def token_file_for(tokens_dir: Path, ep_index: int, entry: dict | None) -> Path:
    """Resolve one episode's .npz: index.json's 'file' wins, else the convention."""
    if entry is not None and entry.get("file"):
        candidate = Path(os.path.expanduser(str(entry["file"])))
        if not candidate.is_absolute():
            candidate = tokens_dir / candidate
        return candidate
    return tokens_dir / f"episode_{ep_index:06d}.npz"


def load_tokens(path: Path, ep_index: int, length: int, entry: dict | None) -> dict:
    """Load and fully validate one episode's token labels."""
    if not path.is_file():
        raise BuildError(f"episode {ep_index}: token file not found: {path}")
    with np.load(path, allow_pickle=False) as data:
        keys = set(data.files)
        for required in ("token", "grip"):
            if required not in keys:
                raise BuildError(f"{path}: missing array '{required}' (has {sorted(keys)})")
        token = np.asarray(data["token"], dtype=np.float32)
        grip = np.asarray(data["grip"], dtype=np.float32)
        meta = {
            "episode_index": npz_int(data["episode_index"]) if "episode_index" in keys else None,
            "source_file": npz_str(data["source_file"]) if "source_file" in keys else None,
            "demo_name": npz_str(data["demo_name"]) if "demo_name" in keys else None,
            "clip": npz_str(data["clip"]) if "clip" in keys else None,
            "n_frames_dataset": (
                npz_int(data["n_frames_dataset"]) if "n_frames_dataset" in keys else None
            ),
        }

    if token.shape != (length, TOKEN_DIM):
        raise BuildError(
            f"{path}: token has shape {token.shape}, expected ({length}, {TOKEN_DIM}) "
            f"-- T must equal the source episode's parquet row count"
        )
    if grip.shape != (length, GRIP_DIM):
        raise BuildError(
            f"{path}: grip has shape {grip.shape}, expected ({length}, {GRIP_DIM})"
        )
    if not np.isfinite(token).all():
        raise BuildError(f"{path}: token contains non-finite values")
    if not np.isfinite(grip).all():
        raise BuildError(f"{path}: grip contains non-finite values")
    token_max = float(np.abs(token).max())
    if token_max > TOKEN_ABS_MAX:
        raise BuildError(
            f"{path}: max |token| = {token_max:.4f} > {TOKEN_ABS_MAX} -- outside the "
            "SONIC FSQ grid bound; the labeller emitted something that is not a "
            "dequantised token"
        )
    if meta["episode_index"] is not None and meta["episode_index"] != ep_index:
        raise BuildError(
            f"{path}: episode_index={meta['episode_index']} but it labels source "
            f"episode {ep_index}"
        )
    if meta["n_frames_dataset"] is not None and meta["n_frames_dataset"] != length:
        raise BuildError(
            f"{path}: n_frames_dataset={meta['n_frames_dataset']} but the source "
            f"episode has {length} frames"
        )
    if entry is not None and entry.get("n_frames_dataset") is not None:
        if int(entry["n_frames_dataset"]) != length:
            raise BuildError(
                f"index.json: episode {ep_index} declares n_frames_dataset="
                f"{entry['n_frames_dataset']} but the source episode has {length} frames"
            )
    grip_lo, grip_hi = float(grip.min()), float(grip.max())
    if grip_lo < -1e-3 or grip_hi > 1.0 + 1e-3:
        log(
            f"WARNING: {path}: grip range [{grip_lo:.4f}, {grip_hi:.4f}] leaves the "
            "[0, 1] open/closed convention"
        )

    clip = meta["clip"]
    if clip is None and entry is not None:
        clip = entry.get("clip")
    meta["clip"] = clip
    meta["token_max_abs"] = token_max
    return {"token": token, "grip": grip, "meta": meta}


# --------------------------------------------------------------- per episode


def write_episode(
    source: dict,
    output: Path,
    ep_index: int,
    labels: dict,
    length: int,
) -> None:
    """Write one episode's relabelled parquet and copy its three mp4s."""
    chunk = ep_index // source["chunks_size"]
    rel_parquet = source["data_path"].format(episode_chunk=chunk, episode_index=ep_index)
    src_parquet = source["root"] / rel_parquet
    dest_parquet = output / rel_parquet
    if not src_parquet.is_file():
        raise BuildError(f"episode {ep_index}: source parquet missing: {src_parquet}")

    table = pq.read_table(src_parquet)
    if table.num_rows != length:
        raise BuildError(
            f"{src_parquet}: {table.num_rows} rows but episodes.jsonl says {length}"
        )
    if "action" not in table.column_names:
        raise BuildError(f"{src_parquet}: no 'action' column")

    action = np.concatenate([labels["token"], labels["grip"]], axis=1).astype(np.float32)
    if action.shape != (length, ACTION_DIM):
        raise BuildError(
            f"episode {ep_index}: built action {action.shape} != ({length}, {ACTION_DIM})"
        )
    action_array = list_column(action)

    # set_column keeps the source column order and every other column's values
    # and type exactly as they were: observation.state, timestamp, frame_index,
    # episode_index, index and task_index are carried across untouched.
    action_idx = table.column_names.index("action")
    table = table.set_column(action_idx, pa.field("action", action_array.type), action_array)

    dest_parquet.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(table, dest_parquet)

    for video_key in source["video_keys"]:
        rel_video = source["video_path"].format(
            episode_chunk=chunk, video_key=video_key, episode_index=ep_index
        )
        src_video = source["root"] / rel_video
        dest_video = output / rel_video
        if not src_video.is_file():
            raise BuildError(f"episode {ep_index}: source video missing: {src_video}")
        dest_video.parent.mkdir(parents=True, exist_ok=True)
        # copy2, never symlink: the fine-tune must survive the label run folder
        # being moved or archived.
        shutil.copy2(src_video, dest_video)
        if dest_video.stat().st_size != src_video.stat().st_size:
            raise BuildError(f"episode {ep_index}: short copy of {src_video} -> {dest_video}")


# ----------------------------------------------------------------- meta files


def build_info(source: dict, selected: list[dict], robot_type: str) -> dict:
    """Source info.json with a 66-D action feature and refreshed totals."""
    info = copy.deepcopy(source["info"])
    info["robot_type"] = robot_type

    action_feature = info["features"]["action"]
    action_feature["dtype"] = "float32"
    action_feature["shape"] = [ACTION_DIM]
    action_feature["names"] = list(ACTION_NAMES)

    total_episodes = len(selected)
    total_frames = int(sum(e["length"] for e in selected))
    info["total_episodes"] = total_episodes
    info["total_frames"] = total_frames
    info["splits"] = {"train": f"0:{total_episodes}"}
    info["total_videos"] = total_episodes * len(source["video_keys"])
    max_chunk = max(e["episode_index"] // source["chunks_size"] for e in selected)
    info["total_chunks"] = max_chunk + 1
    return info


def build_modality(source: dict) -> dict:
    """Source modality.json with the action block swapped for the token layout."""
    modality = copy.deepcopy(source["modality"])
    if "state" not in modality:
        raise BuildError("source meta/modality.json has no 'state' block")
    modality["action"] = {k: dict(v) for k, v in ACTION_SPLIT.items()}
    return modality


def build_provenance(
    source: dict, tokens_dir: Path, per_episode: dict[int, dict], modality_config: Path
) -> dict:
    provenance = copy.deepcopy(source["provenance"])
    for ep_index, extra in per_episode.items():
        key = str(ep_index)
        entry = provenance.get(key)
        if not isinstance(entry, dict):
            entry = {}
        entry.update(extra)
        provenance[key] = entry
    provenance["source_dataset"] = str(source["root"])
    provenance["tokens_dir"] = str(tokens_dir)
    provenance["modality_config"] = str(modality_config)
    provenance["action_layout"] = {
        "dim": ACTION_DIM,
        "names": list(ACTION_NAMES),
        "split": {k: dict(v) for k, v in ACTION_SPLIT.items()},
        "token_abs_max_allowed": TOKEN_ABS_MAX,
    }
    return provenance


# --------------------------------------------------------------------- stages


def run_stats(output: Path, gr00t_root: Path, modality_config: Path) -> None:
    """Regenerate meta/stats.json (+ relative_stats.json) with GR00T's own tool.

    Same invocation as harness/data/convert_hdf5_to_gr00t_v2.py: a subprocess in
    the GR00T checkout, so its import of the modality config cannot collide with
    the in-process import the validation step does afterwards
    (register_modality_config asserts NEW_EMBODIMENT is still free).
    """
    interpreter = gr00t_root / ".venv" / "bin" / "python"
    if not interpreter.is_file():
        interpreter = Path(sys.executable)
    cmd = [
        str(interpreter),
        "gr00t/data/stats.py",
        "--dataset-path",
        str(output),
        "--embodiment-tag",
        "NEW_EMBODIMENT",
        "--modality-config-path",
        str(modality_config),
    ]
    log(f"[stats] {' '.join(cmd)}  (cwd={gr00t_root})")
    result = subprocess.run(cmd, cwd=str(gr00t_root))
    if result.returncode != 0:
        raise BuildError(f"gr00t/data/stats.py failed with rc={result.returncode}")
    stats_path = output / "meta" / "stats.json"
    if not stats_path.is_file():
        raise BuildError("gr00t/data/stats.py did not produce meta/stats.json")
    stats = read_json(stats_path)
    action_stats = stats.get("action")
    if not isinstance(action_stats, dict):
        raise BuildError(f"{stats_path}: no 'action' entry")
    for field in ("mean", "std", "min", "max", "q01", "q99"):
        if field not in action_stats:
            raise BuildError(f"{stats_path}: action stats lack '{field}'")
        if len(action_stats[field]) != ACTION_DIM:
            raise BuildError(
                f"{stats_path}: action.{field} has {len(action_stats[field])} entries, "
                f"expected {ACTION_DIM}"
            )
    log(f"[stats] action stats are {ACTION_DIM}-D; wrote {stats_path}")
    rel_path = output / "meta" / "relative_stats.json"
    if rel_path.is_file():
        log(f"[stats] relative_stats.json present (all action groups are ABSOLUTE, so empty)")


def run_validation(output: Path, modality_config: Path, max_episodes: int) -> None:
    """Load the dataset back through GR00T's own loader, with the sonic config.

    Byte-identical mechanism to the lane A converter: append the config file's
    directory to sys.path, import it by stem (the registration is an import side
    effect), then read MODALITY_CONFIGS["new_embodiment"].
    """
    import importlib

    sys.path.insert(0, str(modality_config.parent))
    importlib.import_module(modality_config.stem)
    from gr00t.configs.data.embodiment_configs import MODALITY_CONFIGS
    from gr00t.data.dataset.lerobot_episode_loader import LeRobotEpisodeLoader

    configs = MODALITY_CONFIGS["new_embodiment"]
    loader = LeRobotEpisodeLoader(str(output), configs)
    log(f"[validate] LeRobotEpisodeLoader: {len(loader)} episodes, fps={loader.fps}")

    stats = loader.get_dataset_statistics()
    for modality in ("state", "action"):
        for key in configs[modality].modality_keys:
            mean = stats[modality][key]["mean"]
            log(f"[validate] stats {modality}.{key}: dim={len(mean)}")

    expected = {key: split["end"] - split["start"] for key, split in ACTION_SPLIT.items()}
    count = len(loader) if not max_episodes else min(len(loader), max_episodes)
    for idx in range(count):
        frame = loader[idx]
        pieces = []
        for column in frame.columns:
            first = frame[column].iloc[0]
            shape = getattr(first, "shape", None)
            pieces.append(
                f"{column}{list(shape) if shape is not None else '=' + str(type(first).__name__)}"
            )
        log(f"[validate] episode {idx}: rows={len(frame)} " + " ".join(pieces))
        for key, width in expected.items():
            first = np.asarray(frame[f"action.{key}"].iloc[0])
            if first.shape != (width,):
                raise BuildError(
                    f"episode {idx}: action.{key} row 0 has shape {first.shape}, "
                    f"expected ({width},)"
                )
        for key in configs["video"].modality_keys:
            first = np.asarray(frame[f"video.{key}"].iloc[0])
            if first.ndim != 3 or first.shape[-1] != 3:
                raise BuildError(f"episode {idx}: video.{key} frame 0 has shape {first.shape}")
            log(f"[validate]   video.{key} frame0 {first.shape} {first.dtype}")


# ----------------------------------------------------------------------- main


def build(args: argparse.Namespace) -> int:
    source_root = Path(os.path.expanduser(args.source)).resolve()
    tokens_dir = Path(os.path.expanduser(args.tokens)).resolve()
    output = Path(os.path.expanduser(args.output)).resolve()
    modality_config = Path(os.path.expanduser(args.modality_config_path)).resolve()
    gr00t_root = Path(os.path.expanduser(args.gr00t_root)).resolve()

    if not source_root.is_dir():
        raise BuildError(f"--source is not a directory: {source_root}")
    if not tokens_dir.is_dir():
        raise BuildError(f"--tokens is not a directory: {tokens_dir}")
    if not modality_config.is_file():
        raise BuildError(f"--modality-config-path does not exist: {modality_config}")
    if output == source_root or source_root in output.parents:
        raise BuildError(
            f"--output {output} would write inside --source {source_root}; pick a "
            "separate directory (the source dataset is never modified)"
        )
    if args.validate and not args.stats:
        # LeRobotEpisodeLoader asserts meta/stats.json exists. Fail here, in a
        # second, instead of after copying every video.
        raise BuildError(
            "--no-validate is required with --no-stats: LeRobotEpisodeLoader "
            "refuses to open a dataset without meta/stats.json"
        )
    guard_output(output)

    source = load_source(source_root)
    log(f"[source] {source_root}")
    log(
        f"[source] {len(source['episodes'])} episodes, "
        f"{source['info'].get('total_frames')} frames, fps={source['info'].get('fps')}, "
        f"videos={source['video_keys']}"
    )
    log(f"[tokens] {tokens_dir}")

    token_index = load_token_index(tokens_dir)
    log(f"[tokens] index.json lists {len(token_index)} episode(s)")

    episodes = list(source["episodes"])
    if args.max_episodes:
        episodes = episodes[: args.max_episodes]
    source_indices = {int(e["episode_index"]) for e in episodes}
    extra = sorted(set(token_index) - source_indices)
    if extra:
        log(
            f"WARNING: index.json has {len(extra)} episode(s) the source dataset does "
            f"not contain (ignored): {extra[:10]}{' ...' if len(extra) > 10 else ''}"
        )
    missing = sorted(source_indices - set(token_index))
    if missing:
        message = (
            f"{len(missing)} source episode(s) have no token label: "
            f"{missing[:10]}{' ...' if len(missing) > 10 else ''}"
        )
        if not args.allow_missing_episodes:
            raise BuildError(
                message + " -- rerun the labeller, or pass --allow-missing-episodes "
                "to build over the labelled subset only"
            )
        log(f"WARNING: {message} -- skipped (--allow-missing-episodes)")
        episodes = [e for e in episodes if int(e["episode_index"]) in token_index]
    if not episodes:
        raise BuildError("no episodes selected")

    (output / "meta").mkdir(parents=True, exist_ok=True)

    selected: list[dict] = []
    per_episode_prov: dict[int, dict] = {}
    for ep_meta in episodes:
        ep_index = int(ep_meta["episode_index"])
        length = int(ep_meta["length"])
        entry = token_index.get(ep_index)
        token_path = token_file_for(tokens_dir, ep_index, entry)
        labels = load_tokens(token_path, ep_index, length, entry)
        meta = labels["meta"]
        log(
            f"[episode {ep_index}] T={length} clip={meta['clip']} "
            f"|token|max={meta['token_max_abs']:.4f} <- {token_path.name}"
        )
        write_episode(source, output, ep_index, labels, length)
        selected.append({"episode_index": ep_index, "length": length})
        per_episode_prov[ep_index] = {
            "clip": meta["clip"],
            "token_file": str(token_path),
            "token_demo_name": meta["demo_name"],
            "token_source_file": meta["source_file"],
            "token_max_abs": meta["token_max_abs"],
            "n_frames_dataset": length,
        }

    info = build_info(source, selected, args.robot_type)
    with open(output / "meta" / "info.json", "w") as handle:
        json.dump(info, handle, indent=4)
    write_jsonl(
        output / "meta" / "episodes.jsonl",
        [e for e in source["episodes"] if int(e["episode_index"]) in per_episode_prov],
    )
    write_jsonl(output / "meta" / "tasks.jsonl", source["tasks"])
    with open(output / "meta" / "modality.json", "w") as handle:
        json.dump(build_modality(source), handle, indent=4)
    with open(output / "meta" / "provenance.json", "w") as handle:
        json.dump(
            build_provenance(source, tokens_dir, per_episode_prov, modality_config),
            handle,
            indent=4,
        )
    log("[meta] wrote info.json, episodes.jsonl, tasks.jsonl, modality.json, provenance.json")

    if args.stats:
        run_stats(output, gr00t_root, modality_config)
    else:
        log("[stats] skipped (--no-stats)")

    if args.validate:
        run_validation(output, modality_config, args.validate_max_episodes)
    else:
        log("[validate] skipped (--no-validate)")

    log(
        f"CONVERT_DONE: {info['total_episodes']} episodes, "
        f"{info['total_frames']} frames -> {output}"
    )
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--source", required=True, help="lane A GR00T v2 dataset root (read-only)"
    )
    parser.add_argument(
        "--tokens", required=True, help="directory of episode_XXXXXX.npz + index.json"
    )
    parser.add_argument("--output", required=True, help="dataset root to create")
    parser.add_argument("--robot-type", default=ROBOT_TYPE)
    parser.add_argument(
        "--max-episodes", type=int, default=0, help="0 = every source episode"
    )
    parser.add_argument(
        "--allow-missing-episodes",
        action="store_true",
        default=False,
        help="build over the labelled subset instead of erroring out; source "
        "episode indices (and therefore the parquet/video filenames and the "
        "global 'index' column) are preserved, so they stay non-contiguous",
    )
    parser.add_argument("--modality-config-path", default=str(DEFAULT_MODALITY_CONFIG))
    parser.add_argument("--stats", dest="stats", action="store_true", default=True)
    parser.add_argument("--no-stats", dest="stats", action="store_false")
    parser.add_argument("--validate", dest="validate", action="store_true", default=True)
    parser.add_argument("--no-validate", dest="validate", action="store_false")
    parser.add_argument(
        "--validate-max-episodes",
        type=int,
        default=0,
        help="0 = validate every episode; the loader decodes a whole episode "
        "per call, so cap this on large datasets",
    )
    parser.add_argument(
        "--gr00t-root",
        default=str(DEFAULT_GR00T_ROOT),
        help="Isaac-GR00T checkout; its .venv python runs gr00t/data/stats.py",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return build(args)
    except Exception as exc:  # noqa: BLE001 - one exit path, always non-zero
        traceback.print_exc()
        print(f"CONVERT_FAILED: {type(exc).__name__}: {exc}", flush=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())
