# ------------------------------------------------------------------- helpers


def log(msg: str) -> None:
    print(msg, flush=True)


def h5_str(value) -> str:
    """Decode an h5py scalar string dataset value (bytes in h5py 3.x)."""
    if isinstance(value, bytes):
        return value.decode("utf-8")
    if isinstance(value, np.ndarray):
        return h5_str(value.item())
    return str(value)


def probe_video(path: Path) -> dict:
    """Return {codec, pix_fmt, width, height, fps} for an mp4, via PyAV."""
    import av

    with av.open(str(path)) as container:
        streams = container.streams.video
        if not streams:
            raise ConvertError(f"no video stream in {path}")
        stream = streams[0]
        ctx = stream.codec_context
        rate = stream.average_rate or ctx.framerate
        return {
            "codec": ctx.name,
            "pix_fmt": str(ctx.pix_fmt),
            "width": int(ctx.width),
            "height": int(ctx.height),
            "fps": float(rate) if rate is not None else None,
        }


def count_frames(path: Path) -> int:
    """Frame count as GR00T's own decoder sees it (torchcodec)."""
    from torchcodec.decoders import VideoDecoder

    return len(VideoDecoder(str(path), device="cpu", dimension_order="NHWC"))


def encode_h264(path: Path, frames: np.ndarray, fps: int) -> None:
    """Encode (T,H,W,3) uint8 RGB to an h264 / yuv420p / crf 20 mp4.

    Mirrors teleop/recorder.py's _encode_video. imageio's FFMPEG plugin is the
    preferred writer (identical settings to the recorder), but imageio_ffmpeg
    is not installed in the GR00T venv on this pod and installing is out of
    scope, so PyAV -- which is installed -- is the fallback. Both produce the
    same codec/pixel format.
    """
    frames = np.asarray(frames)
    if frames.ndim != 4 or frames.shape[-1] != 3 or frames.dtype != np.uint8:
        raise ConvertError(f"expected (T,H,W,3) uint8 frames, got {frames.shape} {frames.dtype}")
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        import imageio.v2 as imageio
        import imageio_ffmpeg  # noqa: F401  (presence check: the plugin needs it)
    except ImportError:
        _encode_h264_pyav(path, frames, fps)
        return
    with imageio.get_writer(
        str(path), format="FFMPEG", mode="I", fps=fps, codec="libx264",
        macro_block_size=1, output_params=["-pix_fmt", "yuv420p", "-crf", "20"],
    ) as writer:
        for frame in frames:
            writer.append_data(np.asarray(frame))


def _encode_h264_pyav(path: Path, frames: np.ndarray, fps: int) -> None:
    import av

    height, width = int(frames.shape[1]), int(frames.shape[2])
    with av.open(str(path), mode="w") as container:
        stream = container.add_stream("libx264", rate=int(fps))
        stream.width = width
        stream.height = height
        stream.pix_fmt = "yuv420p"
        stream.options = {"crf": "20"}
        for frame in frames:
            av_frame = av.VideoFrame.from_ndarray(np.ascontiguousarray(frame), format="rgb24")
            for packet in stream.encode(av_frame):
                container.mux(packet)
        for packet in stream.encode():
            container.mux(packet)


def list_column(values: np.ndarray) -> pa.Array:
    """(T,D) float32 -> arrow list<float32>, one D-vector per row.

    list<float32> (not fixed_size_list) is what LeRobot v2.1 writes and what
    makes ``pd.read_parquet`` hand each cell back as a float32 np.ndarray --
    which lerobot_episode_loader._extract_joint_groups requires
    (``isinstance(df[key].iloc[0], np.ndarray)``).
    """
    values = np.ascontiguousarray(values, dtype=np.float32)
    rows, dim = values.shape
    offsets = pa.array(np.arange(0, rows * dim + 1, dim, dtype=np.int32), type=pa.int32())
    flat = pa.array(values.reshape(-1), type=pa.float32())
    return pa.ListArray.from_arrays(offsets, flat)


