def resolve_inputs(patterns: list[str]) -> list[Path]:
    paths: list[Path] = []
    for pattern in patterns:
        expanded = os.path.expanduser(pattern)
        hits = sorted(glob.glob(expanded))
        if not hits:
            candidate = Path(expanded)
            if candidate.is_file():
                hits = [str(candidate)]
        if not hits:
            raise ConvertError(f"--input matched nothing: {pattern}")
        for hit in hits:
            resolved = Path(hit).resolve()
            if resolved not in paths:
                paths.append(resolved)
    return paths


def guard_output(output: Path) -> None:
    """Refuse to write on top of an existing dataset (never delete, rule o)."""
    if not output.exists():
        return
    if not output.is_dir():
        raise ConvertError(f"--output exists and is not a directory: {output}")
    existing = [
        p
        for p in (output / "meta" / "info.json", output / "meta" / "modality.json")
        if p.exists()
    ] + sorted(output.glob("data/chunk-*/episode_*.parquet"))[:1]
    if existing:
        raise ConvertError(
            f"--output already contains a dataset ({existing[0]}). "
            "Refusing to overwrite; nothing on this pod is ever deleted "
            "(AGENTS.md rule o) -- pick a fresh --output directory."
        )


VIDEO_SIZE: tuple[int, int] | None = None  # (W, H) every mp4 must have; set from --video-size


def parse_size(text: str | None) -> tuple[int, int] | None:
    if not text:
        return None
    w, h = text.lower().split("x")
    return int(w), int(h)


def transcode_to_size(src: Path, dest: Path, size: tuple[int, int]) -> None:
    """Rescale an mp4 to WxH with ffmpeg (area filter, h264/yuv420p/crf 20), frame count kept.

    GR00T stacks all camera views into ONE tensor after its shortest-edge resize, so every view
    must resize to the same shape — a 640x360 top and 424x240 wrists become 455x256 vs 452x256
    and `torch.stack` fails in the first batch (lane_a finetune attempt 3, 2026-09-03).
    """
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        raise ConvertError("ffmpeg not found on PATH; needed to rescale videos to --video-size")
    dest.parent.mkdir(parents=True, exist_ok=True)
    cmd = [ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-i", str(src),
           "-vf", f"scale={size[0]}:{size[1]}:flags=area", "-vsync", "passthrough",
           "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "20", "-movflags", "+faststart", str(dest)]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    if result.returncode != 0:
        raise ConvertError(f"ffmpeg failed rescaling {src} -> {dest}: {result.stderr.strip()[:400]}")


def place_video(demo: dict, camera: str, dest: Path, fps: int, length: int) -> dict:
    """Copy (or encode / rescale) one camera's mp4 into the dataset and verify it."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    source = demo["videos"][camera]
    if isinstance(source, str):
        src_path = Path(demo["source_dir"]) / source
        if not src_path.is_file():
            raise ConvertError(f"{demo['demo_name']}: obs/{camera} points at a missing file {src_path}")
        probe = probe_video(src_path)
        size_ok = VIDEO_SIZE is None or (probe["width"], probe["height"]) == VIDEO_SIZE
        if probe["codec"] == "h264" and probe["pix_fmt"] == "yuv420p" and size_ok:
            shutil.copy2(src_path, dest)  # already the target codec and size: no transcode
        elif not size_ok:
            log(f"    rescaling {camera} {probe['width']}x{probe['height']} -> {VIDEO_SIZE[0]}x{VIDEO_SIZE[1]}")
            transcode_to_size(src_path, dest, VIDEO_SIZE)
        else:
            log(
                f"    transcoding {camera} ({probe['codec']}/{probe['pix_fmt']} "
                f"-> h264/yuv420p)"
            )
            from torchcodec.decoders import VideoDecoder

            decoder = VideoDecoder(str(src_path), device="cpu", dimension_order="NHWC")
            frames = decoder.get_frames_at(indices=list(range(len(decoder)))).data.numpy()
            encode_h264(dest, frames, fps)
    else:
        if VIDEO_SIZE is not None and (source.shape[2], source.shape[1]) != VIDEO_SIZE:
            import cv2

            source = np.stack([cv2.resize(f, VIDEO_SIZE, interpolation=cv2.INTER_AREA) for f in source])
        encode_h264(dest, source, fps)

    probe = probe_video(dest)
    if probe["codec"] != "h264" or probe["pix_fmt"] != "yuv420p":
        raise ConvertError(f"{dest}: expected h264/yuv420p, got {probe['codec']}/{probe['pix_fmt']}")
    if VIDEO_SIZE is not None and (probe["width"], probe["height"]) != VIDEO_SIZE:
        raise ConvertError(f"{dest}: is {probe['width']}x{probe['height']}, expected {VIDEO_SIZE}")
    frames = count_frames(dest)
    if frames != length:
        raise ConvertError(
            f"{dest}: has {frames} frames but the episode has {length} samples"
        )
    return probe


def write_episode(
    output: Path, ep_index: int, demo: dict, fps: int, index_offset: int
) -> dict[str, dict]:
    """Write one episode's parquet + three mp4s. Returns per-camera video meta."""
    length = demo["length"]
    chunk = ep_index // CHUNKS_SIZE
    parquet_path = output / DATA_PATH_TMPL.format(episode_chunk=chunk, episode_index=ep_index)
    parquet_path.parent.mkdir(parents=True, exist_ok=True)

    table = pa.table(
        {
            "observation.state": list_column(demo["state"]),
            "action": list_column(demo["action"]),
            "timestamp": pa.array(
                (np.arange(length, dtype=np.float32) / np.float32(fps)), type=pa.float32()
            ),
            "frame_index": pa.array(np.arange(length, dtype=np.int64), type=pa.int64()),
            "episode_index": pa.array(
                np.full(length, ep_index, dtype=np.int64), type=pa.int64()
            ),
            "index": pa.array(
                np.arange(index_offset, index_offset + length, dtype=np.int64), type=pa.int64()
            ),
            "task_index": pa.array(np.zeros(length, dtype=np.int64), type=pa.int64()),
        }
    )
    pq.write_table(table, parquet_path)

    video_meta = {}
    for camera in CAMERAS:
        dest = output / VIDEO_PATH_TMPL.format(
            episode_chunk=chunk,
            video_key=f"observation.images.{camera}",
            episode_index=ep_index,
        )
        video_meta[camera] = place_video(demo, camera, dest, fps, length)
    return video_meta


def run_stats(output: Path, gr00t_root: Path, modality_config: Path) -> None:
    interpreter = gr00t_root / ".venv" / "bin" / "python"
    if not interpreter.is_file():
        interpreter = Path(sys.executable)
    cmd = [
        str(interpreter),
        "gr00t/data/stats.py",
        "--dataset-path",
        str(output),
        "--embodiment-tag",
        "NEW_EMBODIMENT",
        "--modality-config-path",
        str(modality_config),
    ]
    log(f"[stats] {' '.join(cmd)}  (cwd={gr00t_root})")
    result = subprocess.run(cmd, cwd=str(gr00t_root))
    if result.returncode != 0:
        raise ConvertError(f"gr00t/data/stats.py failed with rc={result.returncode}")
    if not (output / "meta" / "stats.json").is_file():
        raise ConvertError("gr00t/data/stats.py did not produce meta/stats.json")


def run_validation(output: Path, modality_config: Path, max_episodes: int) -> None:
    """Load the dataset back through GR00T's own loader."""
    import importlib

    sys.path.insert(0, str(modality_config.parent))
    importlib.import_module(modality_config.stem)
    from gr00t.configs.data.embodiment_configs import MODALITY_CONFIGS
    from gr00t.data.dataset.lerobot_episode_loader import LeRobotEpisodeLoader

    configs = MODALITY_CONFIGS["new_embodiment"]
    loader = LeRobotEpisodeLoader(str(output), configs)
    log(f"[validate] LeRobotEpisodeLoader: {len(loader)} episodes, fps={loader.fps}")

    stats = loader.get_dataset_statistics()
    for modality in ("state", "action"):
        for key in configs[modality].modality_keys:
            mean = stats[modality][key]["mean"]
            log(f"[validate] stats {modality}.{key}: dim={len(mean)}")

    count = len(loader) if not max_episodes else min(len(loader), max_episodes)
    for idx in range(count):
        frame = loader[idx]
        pieces = []
        for column in frame.columns:
            first = frame[column].iloc[0]
            shape = getattr(first, "shape", None)
            pieces.append(f"{column}{list(shape) if shape is not None else '=' + str(type(first).__name__)}")
        log(f"[validate] episode {idx}: rows={len(frame)} " + " ".join(pieces))
        for key in configs["video"].modality_keys:
            first = frame[f"video.{key}"].iloc[0]
            arr = np.asarray(first)
            if arr.ndim != 3 or arr.shape[-1] != 3:
                raise ConvertError(f"episode {idx}: video.{key} frame 0 has shape {arr.shape}")
            log(f"[validate]   video.{key} frame0 {arr.shape} {arr.dtype}")


