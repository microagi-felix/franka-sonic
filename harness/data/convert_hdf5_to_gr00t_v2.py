def convert(args: argparse.Namespace) -> int:
    global LABEL_MODE, MAX_DELTA_RAD, VIDEO_SIZE
    LABEL_MODE, MAX_DELTA_RAD = args.joint_label, args.max_delta_rad
    VIDEO_SIZE = parse_size(args.video_size)
    log(f"[label] arm action = {joint_labels.describe(LABEL_MODE, MAX_DELTA_RAD)}")
    log(f"[video] single resolution for all cameras: {VIDEO_SIZE or 'as exported (no rescale)'}")
    output = Path(os.path.expanduser(args.output)).resolve()
    modality_config = Path(os.path.expanduser(args.modality_config_path)).resolve()
    gr00t_root = Path(os.path.expanduser(args.gr00t_root)).resolve()
    if not modality_config.is_file():
        raise ConvertError(f"--modality-config-path does not exist: {modality_config}")

    inputs = resolve_inputs(args.input)
    log(f"[input] {len(inputs)} HDF5 file(s):")
    for path in inputs:
        log(f"  {path}")
    guard_output(output)

    demos = collect_demos(inputs, args.skip_failed_replays, args.max_episodes)
    if not demos:
        raise ConvertError("no episodes selected (all skipped?)")
    for demo in demos:
        if demo["file_fps"] is not None and abs(demo["file_fps"] - args.fps) > 1e-6:
            log(
                f"WARNING: {demo['source_file']} was recorded at fps={demo['file_fps']} "
                f"but --fps {args.fps} was requested; using {args.fps} for timestamps."
            )
    log(f"[select] {len(demos)} episode(s), {sum(d['length'] for d in demos)} frames")

    (output / "meta").mkdir(parents=True, exist_ok=True)

    episodes_meta: list[dict] = []
    provenance: dict[str, dict] = {}
    video_meta: dict[str, dict] = {}
    index_offset = 0
    for ep_index, demo in enumerate(demos):
        log(f"[episode {ep_index}] {demo['source_file']}:{demo['demo_name']} T={demo['length']}")
        per_camera = write_episode(output, ep_index, demo, args.fps, index_offset)
        for camera, probe in per_camera.items():
            if camera not in video_meta:
                video_meta[camera] = probe
            elif (probe["height"], probe["width"]) != (
                video_meta[camera]["height"],
                video_meta[camera]["width"],
            ):
                raise ConvertError(
                    f"episode {ep_index}: camera {camera} is "
                    f"{probe['width']}x{probe['height']} but earlier episodes are "
                    f"{video_meta[camera]['width']}x{video_meta[camera]['height']}; "
                    "one resolution per camera is required by meta/info.json"
                )
        index_offset += demo["length"]
        episodes_meta.append(
            {"episode_index": ep_index, "tasks": [args.task], "length": demo["length"]}
        )
        provenance[str(ep_index)] = {
            "source_file": demo["source_file"],
            "demo_name": demo["demo_name"],
            "length": demo["length"],
            "replay_success": demo["replay_success"],
        }

    info = build_info(args.fps, demos, video_meta)
    with open(output / "meta" / "info.json", "w") as handle:
        json.dump(info, handle, indent=4)
    write_jsonl(output / "meta" / "episodes.jsonl", episodes_meta)
    write_jsonl(output / "meta" / "tasks.jsonl", [{"task_index": 0, "task": args.task}])
    with open(output / "meta" / "modality.json", "w") as handle:
        json.dump(build_modality(), handle, indent=4)
    provenance["joint_label"] = {"mode": LABEL_MODE, "max_delta_rad": MAX_DELTA_RAD,
                                 "description": joint_labels.describe(LABEL_MODE, MAX_DELTA_RAD)}
    provenance["video_size"] = list(VIDEO_SIZE) if VIDEO_SIZE else None
    with open(output / "meta" / "provenance.json", "w") as handle:
        json.dump(provenance, handle, indent=4)
    log(f"[meta] wrote info.json, episodes.jsonl, tasks.jsonl, modality.json, provenance.json")

    if args.stats:
        run_stats(output, gr00t_root, modality_config)
    else:
        log("[stats] skipped (--no-stats)")

    if args.validate:
        run_validation(output, modality_config, args.validate_max_episodes)
    else:
        log("[validate] skipped (--no-validate)")

    log(
        f"CONVERT_DONE: {info['total_episodes']} episodes, "
        f"{info['total_frames']} frames -> {output}"
    )
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--input", nargs="+", required=True,
        help="one or more HDF5 paths or globs (quote globs so the shell keeps them)",
    )
    parser.add_argument("--output", required=True, help="dataset root to create")
    parser.add_argument("--fps", type=int, default=50)
    parser.add_argument(
        "--task", default="hand the block from the left arm to the right",
        help="the single task string; also the language annotation",
    )
    parser.add_argument(
        "--max-episodes", type=int, default=0, help="0 = every episode found"
    )
    parser.add_argument(
        "--skip-failed-replays", dest="skip_failed_replays",
        action="store_true", default=True,
        help="drop demos with replay_success=False (default)",
    )
    parser.add_argument(
        "--no-skip-failed-replays", dest="skip_failed_replays", action="store_false"
    )
    parser.add_argument(
        "--joint-label", choices=joint_labels.JOINT_LABELS, default=joint_labels.DEFAULT_JOINT_LABEL,
        help="arm action label (harness/data/joint_labels.py); the A-oracle must replay the same one",
    )
    parser.add_argument("--max-delta-rad", type=float, default=joint_labels.DEFAULT_MAX_DELTA_RAD,
                        help="per-step move bound for --joint-label ik_target_delta")
    parser.add_argument("--video-size", default="640x360",
                        help="WxH every camera video must have (GR00T stacks the views: one resolution); "
                             "mismatching mp4s are rescaled with ffmpeg. '' = keep as exported")
    parser.add_argument("--modality-config-path", default=str(DEFAULT_MODALITY_CONFIG))
    parser.add_argument("--stats", dest="stats", action="store_true", default=True)
    parser.add_argument("--no-stats", dest="stats", action="store_false")
    parser.add_argument("--validate", dest="validate", action="store_true", default=True)
    parser.add_argument("--no-validate", dest="validate", action="store_false")
    parser.add_argument(
        "--validate-max-episodes", type=int, default=0,
        help="0 = validate every episode; the loader decodes a whole episode "
             "per call, so cap this on large datasets",
    )
    parser.add_argument(
        "--gr00t-root", default=str(DEFAULT_GR00T_ROOT),
        help="Isaac-GR00T checkout; its .venv python runs gr00t/data/stats.py",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return convert(args)
    except Exception as exc:  # noqa: BLE001 - one exit path, always non-zero
        traceback.print_exc()
        print(f"CONVERT_FAILED: {type(exc).__name__}: {exc}", flush=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())
