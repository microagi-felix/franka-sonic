def read_demo(group: h5py.Group, name: str) -> dict:
    """Pull the arrays lane A needs out of one data/demo_{i} group."""
    if "num_samples" not in group.attrs:
        raise ConvertError(f"{name}: missing attr num_samples")
    length = int(group.attrs["num_samples"])
    if length <= 0:
        raise ConvertError(f"{name}: num_samples={length}")

    obs = group.get("obs")
    if obs is None:
        raise ConvertError(f"{name}: missing obs group")

    def arr(key: str, path: str, width: int) -> np.ndarray:
        node = obs if path == "obs" else group
        if key not in node:
            raise ConvertError(f"{name}: missing {path}/{key}")
        value = np.asarray(node[key][()], dtype=np.float32)
        if value.shape != (length, width):
            raise ConvertError(
                f"{name}: {path}/{key} has shape {value.shape}, expected ({length}, {width})"
            )
        return value

    actions = arr("actions", "demo", 16)
    state = np.concatenate(
        [
            arr("joint_pos_left", "obs", 7),
            arr("joint_pos_right", "obs", 7),
            arr("gripper_left", "obs", 1),
            arr("gripper_right", "obs", 1),
        ],
        axis=1,
    )
    # grip command: recorder +1 = open / -1 = closed  ->  dataset 1 = closed
    grip_cmd = (1.0 - actions[:, [7, 15]]) / 2.0
    # arm label: see harness/data/joint_labels.py (decision + measurements); LABEL_MODE is set
    # from --joint-label in convert() so the oracle replay and the dataset agree by construction.
    action = np.concatenate(
        [
            joint_labels.arm_label(arr("joint_pos_left", "obs", 7), arr("joint_target_left", "obs", 7),
                                   LABEL_MODE, MAX_DELTA_RAD),
            joint_labels.arm_label(arr("joint_pos_right", "obs", 7), arr("joint_target_right", "obs", 7),
                                   LABEL_MODE, MAX_DELTA_RAD),
            grip_cmd,
        ],
        axis=1,
    ).astype(np.float32)

    if state.shape != (length, VECTOR_DIM) or action.shape != (length, VECTOR_DIM):
        raise ConvertError(f"{name}: built vectors {state.shape}/{action.shape} != ({length}, 16)")
    for label, value in (("observation.state", state), ("action", action)):
        if not np.isfinite(value).all():
            raise ConvertError(f"{name}: {label} contains non-finite values")

    videos: dict[str, object] = {}
    for camera in CAMERAS:
        if camera not in obs:
            raise ConvertError(f"{name}: missing obs/{camera}")
        node = obs[camera]
        if node.shape == () or node.dtype.kind in ("O", "S", "U"):
            videos[camera] = h5_str(node[()])  # relative path to an mp4
        else:
            videos[camera] = np.asarray(node[()])  # raw (T,H,W,3) uint8

    replay_success = group.attrs.get("replay_success", None)
    if replay_success is not None:
        replay_success = bool(replay_success)

    return {
        "length": length,
        "state": state,
        "action": action,
        "videos": videos,
        "replay_success": replay_success,
        "video_backed": bool(group.attrs.get("images_video_backed", False)),
    }


def collect_demos(paths: list[Path], skip_failed: bool, max_episodes: int) -> list[dict]:
    """Walk every input file in order and return the demos to convert."""
    selected: list[dict] = []
    for path in paths:
        with h5py.File(path, "r") as handle:
            file_fps = handle.attrs.get("fps", None)
            file_task = handle.attrs.get("task", None)
            if "data" not in handle:
                raise ConvertError(f"{path}: no /data group")
            names = sorted(
                (n for n in handle["data"] if n.startswith("demo_")),
                key=lambda n: int(n.split("_")[1]),
            )
            if not names:
                raise ConvertError(f"{path}: /data holds no demo_* groups")
            for name in names:
                if max_episodes and len(selected) >= max_episodes:
                    return selected
                group = handle["data"][name]
                success = group.attrs.get("replay_success", None)
                if skip_failed and success is not None and not bool(success):
                    log(f"  skip {path.name}:{name} (replay_success=False)")
                    continue
                demo = read_demo(group, f"{path.name}:{name}")
                demo["source_file"] = str(path)
                demo["source_dir"] = str(path.parent)
                demo["demo_name"] = name
                demo["file_fps"] = None if file_fps is None else float(file_fps)
                demo["file_task"] = None if file_task is None else h5_str(file_task)
                selected.append(demo)
    return selected


