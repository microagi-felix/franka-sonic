#!/usr/bin/env python
"""Convert training-schema FR3 handover HDF5 exports into a GR00T-flavored
LeRobot v2.1 dataset (lane A, joint-target actions).

Run it with the GR00T interpreter, which owns h5py / pyarrow / torchcodec:

    ~/Isaac-GR00T/.venv/bin/python harness/data/convert_hdf5_to_gr00t_v2.py \\
        --input '~/runs/franka-sonic/shared/2026-09-03_demos/out/*.hdf5' \\
        --output <run>/out/gr00t_v2 --fps 50 \\
        --task "hand the block from the left arm to the right"

INPUT (written by teleop/recorder.py of franka-bimanual-isaac-sim, video-backed)
------------------------------------------------------------------------------
file attrs: fps, task, source
data/demo_{i}: attrs num_samples=T, images_video_backed=True, [replay_success]
  actions            (T,16) f32  IK-Abs [pos3 quat_wxyz4 grip, pos3 quat_wxyz4 grip]
                                 with grip **+1 = open, -1 = closed**
  obs/joint_pos_left     (T,7)   measured joint positions
  obs/joint_pos_right    (T,7)
  obs/gripper_left       (T,1)   [0,1], 1 = closed
  obs/gripper_right      (T,1)
  obs/joint_target_left  (T,7)   differential-IK joint targets = lane A's labels
  obs/joint_target_right (T,7)
  obs/top | wrist_left | wrist_right
                                 scalar string dataset holding a path RELATIVE
                                 to the HDF5's directory to an h264/yuv420p mp4
                                 at `fps` with exactly T frames. A raw
                                 (T,H,W,3) uint8 array is also accepted and is
                                 encoded here (libx264, yuv420p, crf 20).
  [obs/eef_*, obs/object, initial_cube_pose] are carried only as provenance.

OUTPUT (GR00T-flavored LeRobot v2.1, the layout gr00t/data/dataset/
lerobot_episode_loader.py reads)
------------------------------------------------------------------------------
    <output>/data/chunk-{ep//1000:03d}/episode_{ep:06d}.parquet
    <output>/videos/chunk-{c:03d}/observation.images.{top,wrist_left,wrist_right}/episode_{ep:06d}.mp4
    <output>/meta/{info.json,episodes.jsonl,tasks.jsonl,modality.json,provenance.json}
    <output>/meta/stats.json          (generated by gr00t/data/stats.py unless --no-stats)

16-D vectors, DATASET order (differs from the sim's wire order on purpose;
harness/lane_a/serve_gr00t_joint.py owns the conversion):

    observation.state[t] = [joint_pos_left(7), joint_pos_right(7),
                            gripper_left, gripper_right]
    action[t]            = [joint_target_left(7), joint_target_right(7),
                            grip_l_cmd, grip_r_cmd]

Gripper actions are rescaled from the recorder's +-1 convention to [0,1] with
**1 = closed**, matching the state columns: cmd = (1 - actions[t, 7|15]) / 2.

Refuses to write into a directory that already holds a dataset. Nothing is ever
deleted (AGENTS.md rule o); a stale output directory is an error, not a target.
Prints `CONVERT_DONE: <N> episodes, <F> frames -> <dir>` on success and exits
non-zero on any failure.
"""

